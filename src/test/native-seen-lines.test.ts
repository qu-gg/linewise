import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import type * as Native from '@oh-my-pi/pi-natives';

const require = createRequire(import.meta.url);
let native: typeof Native | undefined;
try {
  native = require('@oh-my-pi/pi-natives-linux-x64') as typeof Native;
} catch {
  native = undefined;
}
const supported = process.platform === 'linux' && process.arch === 'x64' && Boolean(native);

function policy(cwd: string) {
  return {
    cwd,
    mode: 'hashline',
    allowFuzzy: false,
    fuzzyThreshold: 1,
    enforceSeenLines: true,
    maxColumns: 0,
    blockAutoGenerated: true,
    planActive: false,
    urlSchemes: [],
    urlAliasSchemes: [],
    planWritableRoots: [],
    homeDir: os.homedir(),
    rawInput: false,
  };
}

async function fixture(context: { after(callback: () => Promise<void>): void }, body: string) {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'omp-seen-lines-'));
  const file = path.join(directory, 'file.txt');
  await writeFile(file, body);
  context.after(() => rm(directory, { recursive: true, force: true }));
  return { directory, file };
}

test(
  'plain read bodies have no provenance and remain editable',
  { skip: !supported },
  async (context) => {
    const { directory, file } = await fixture(context, 'a\nb\nc\n');
    const store = new native!.EditStore();
    const tag = store.recordSnapshotFile(file)!;
    assert.equal(store.seenLines(file, tag), null);
    const session = new native!.EditSession(store, policy(directory));
    try {
      session.setArgsJson(JSON.stringify({ input: `[${file}#${tag}]\nPUT 2.=2:\n+B\n` }));
      session.finish();
      const outcome = await session.apply({ lspFlush: false }, async (_error, request) => ({
        written: request.content ?? '',
      }));
      assert.equal(outcome.isError, false, outcome.text);
    } finally {
      session.close();
    }
  },
);

test(
  'folded hashline bodies reject unseen lines and retain the store for retry',
  { skip: !supported },
  async (context) => {
    const { directory, file } = await fixture(context, 'a\nb\nc\nd\ne\n');
    const store = new native!.EditStore();
    const tag = store.recordSnapshotFile(file)!;
    store.recordSeenLinesFromBody(file, tag, '1:a\n2:b\n…\n5:e');
    const patch = `[${file}#${tag}]\nPUT 3.=3:\n+C\n`;
    for (const expected of [true, false]) {
      const session = new native!.EditSession(store, policy(directory));
      try {
        session.setArgsJson(JSON.stringify({ input: patch }));
        session.finish();
        const outcome = await session.apply({ lspFlush: false }, async (_error, request) => ({
          written: request.content ?? '',
        }));
        assert.equal(outcome.isError, expected, outcome.text);
        if (expected) assert.equal(outcome.errorKind, 'unseen_lines');
      } finally {
        session.close();
      }
    }
  },
);
