import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { installNativeEdit } from '../dist/native-edit.js';

export default async function installProbe(api) {
  await installNativeEdit(api);
  api.registerCommand('vs-omp-native-probe', {
    description: 'Run the disposable native parser checks',
    handler: async () => {
      try {
        await api.setActiveTools(['read', 'edit']);
        const native = await import('@oh-my-pi/pi-natives');
        const root = dirname(process.env.VS_OMP_FIXTURE_CONTEXT);
        const source = join(root, 'probe.txt');
        await writeFile(source, 'before\n');
        const requests = [];
        for (const operation of ['PUT 1.=1:\n+after', 'REM', 'MV moved.txt', 'create']) {
          const store = new native.EditStore();
          const tag = store.recordSnapshot(source, 'before\n');
          const session = new native.EditSession(store, {
            cwd: root,
            mode: 'hashline',
            allowFuzzy: false,
            fuzzyThreshold: 1,
            enforceSeenLines: true,
            maxColumns: 0,
            blockAutoGenerated: true,
            planActive: false,
            urlSchemes: [],
            urlAliasSchemes: [],
            planWritableRoots: [],
            homeDir: root,
            rawInput: false,
          });
          try {
            session.setArgsJson(
              JSON.stringify({
                input:
                  operation === 'create'
                    ? '[transport.json]\nPUT <1:\n+{}'
                    : `[probe.txt#${tag}]\n${operation}`,
              }),
            );
            session.finish();
            const result = await session.apply({ lspFlush: false }, async (error, request) => {
              assert.ifError(error);
              requests.push(request);
              return { written: request.content ?? '' };
            });
            assert.equal(result.isError, operation === 'create', result.text);
            assert.equal(await readFile(source, 'utf8'), 'before\n');
          } finally {
            session.close();
          }
        }
        await writeFile(
          join(dirname(process.env.VS_OMP_FIXTURE_CONTEXT), 'native-api.json'),
          JSON.stringify({
            requests,
            session: Object.getOwnPropertyNames(native.EditSession.prototype),
            store: Object.getOwnPropertyNames(native.EditStore.prototype),
            inspect: native.editInspect(
              'hashline',
              JSON.stringify({ input: '[probe.txt#ABCD]\nREM' }),
            ),
            factory: typeof api.pi?.BUILTIN_TOOLS?.read,
            storeFactory: typeof api.pi?.getEditStore,
          }),
          { mode: 0o600 },
        );
      } catch (error) {
        await writeFile(
          join(dirname(process.env.VS_OMP_FIXTURE_CONTEXT), 'native-api.json'),
          JSON.stringify({ error: String(error), stack: error.stack }),
          { mode: 0o600 },
        );
      }
    },
  });
}
